const { withXcodeProject, IOSConfig } = require('expo/config-plugins');

const PLUGIN_FILE_NAME = 'GuanacoRefreshCookieInterceptor.m';

const OBJC_INTERCEPTOR_SOURCE = `// Generated by plugins/withIosRefreshCookieMerge.js
// Fixes React Native iOS RCTNetworking comma-folding when NSHTTPCookieStorage and explicit Cookie
// headers both supply vikunja_refresh_token, ensuring RFC 6265 '; '-separated pairs where the
// authoritative SecureStore-backed vikunja_refresh_token (appended last) wins.

#import <Foundation/Foundation.h>
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wnullability-completeness"
#import <React/RCTHTTPRequestHandler.h>

static NSString *GuanacoNormalizeCookieHeader(NSString *rawCookie)
{
  if (rawCookie == nil || rawCookie.length == 0) {
    return nil;
  }
  NSRange refreshRange = [rawCookie rangeOfString:@"vikunja_refresh_token="
                                          options:NSCaseInsensitiveSearch];
  if (refreshRange.location == NSNotFound) {
    return nil;
  }

  NSCharacterSet *delimiters = [NSCharacterSet characterSetWithCharactersInString:@";,"];
  NSCharacterSet *whitespace = [NSCharacterSet whitespaceAndNewlineCharacterSet];
  NSCharacterSet *quotes = [NSCharacterSet characterSetWithCharactersInString:@"\\""];

  NSArray<NSString *> *segments = [rawCookie componentsSeparatedByCharactersInSet:delimiters];
  NSMutableArray<NSString *> *orderedKeys = [NSMutableArray array];
  NSMutableDictionary<NSString *, NSString *> *otherCookiesByLowerName = [NSMutableDictionary dictionary];
  NSString *authoritativeRefreshToken = nil;

  for (NSString *segment in segments) {
    NSString *trimmed = [segment stringByTrimmingCharactersInSet:whitespace];
    if (trimmed.length == 0) {
      continue;
    }
    NSRange eqRange = [trimmed rangeOfString:@"="];
    if (eqRange.location == NSNotFound || eqRange.location == 0) {
      continue;
    }
    NSString *name = [[trimmed substringToIndex:eqRange.location] stringByTrimmingCharactersInSet:whitespace];
    NSString *value = [[trimmed substringFromIndex:eqRange.location + 1] stringByTrimmingCharactersInSet:whitespace];
    if (name.length == 0) {
      continue;
    }

    if ([name caseInsensitiveCompare:@"vikunja_refresh_token"] == NSOrderedSame) {
      NSString *unquoted = [value stringByTrimmingCharactersInSet:quotes];
      unquoted = [unquoted stringByTrimmingCharactersInSet:whitespace];
      if (unquoted.length > 0) {
        authoritativeRefreshToken = unquoted;
      }
    } else {
      NSString *lowerName = name.lowercaseString;
      if (otherCookiesByLowerName[lowerName] == nil) {
        [orderedKeys addObject:lowerName];
      }
      otherCookiesByLowerName[lowerName] = [NSString stringWithFormat:@"%@=%@", name, value];
    }
  }

  NSMutableArray<NSString *> *mergedPairs = [NSMutableArray arrayWithCapacity:orderedKeys.count + 1];
  for (NSString *lowerName in orderedKeys) {
    NSString *pair = otherCookiesByLowerName[lowerName];
    if (pair != nil) {
      [mergedPairs addObject:pair];
    }
  }
  if (authoritativeRefreshToken != nil) {
    [mergedPairs addObject:[NSString stringWithFormat:@"vikunja_refresh_token=%@", authoritativeRefreshToken]];
  }

  return mergedPairs.count > 0 ? [mergedPairs componentsJoinedByString:@"; "] : nil;
}

@interface GuanacoRefreshCookieInterceptor : NSObject
@end

@implementation GuanacoRefreshCookieInterceptor

+ (void)load
{
  static dispatch_once_t onceToken;
  dispatch_once(&onceToken, ^{
    RCTSetCustomHTTPRequestInterceptor(^NSURLRequest *_Nullable(NSURLRequest *request) {
      if (request == nil) {
        return nil;
      }
      NSString *rawCookie = [request valueForHTTPHeaderField:@"Cookie"];
      NSString *normalized = GuanacoNormalizeCookieHeader(rawCookie);
      if (normalized == nil || [normalized isEqualToString:rawCookie]) {
        return nil;
      }
      NSMutableURLRequest *mutableRequest = [request mutableCopy];
      [mutableRequest setValue:normalized forHTTPHeaderField:@"Cookie"];
      return [mutableRequest copy];
    });
  });
}

@end
#pragma clang diagnostic pop
`;

/**
 * Pure-JS mirror of `GuanacoNormalizeCookieHeader` for unit testing.
 */
function normalizeIosCookieHeader(rawCookie) {
  if (!rawCookie || typeof rawCookie !== 'string') return null;
  if (!/vikunja_refresh_token=/i.test(rawCookie)) return null;

  const segments = rawCookie.split(/[;,]/);
  const orderedKeys = [];
  const otherByLower = new Map();
  let authoritativeRefreshToken = null;

  for (const seg of segments) {
    const trimmed = seg.trim();
    if (!trimmed) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx <= 0) continue;
    const name = trimmed.slice(0, eqIdx).trim();
    const val = trimmed.slice(eqIdx + 1).trim();
    if (!name) continue;

    if (name.toLowerCase() === 'vikunja_refresh_token') {
      const unquoted = val.replace(/^"+|"+$/g, '').trim();
      if (unquoted.length > 0) {
        authoritativeRefreshToken = unquoted;
      }
    } else {
      const lower = name.toLowerCase();
      if (!otherByLower.has(lower)) {
        orderedKeys.push(lower);
      }
      otherByLower.set(lower, `${name}=${val}`);
    }
  }

  const merged = orderedKeys.map((k) => otherByLower.get(k)).filter(Boolean);
  if (authoritativeRefreshToken) {
    merged.push(`vikunja_refresh_token=${authoritativeRefreshToken}`);
  }
  return merged.length > 0 ? merged.join('; ') : null;
}

function withIosRefreshCookieMerge(config) {
  return withXcodeProject(config, (modConfig) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(modConfig.modRequest.projectRoot);
    modConfig.modResults = IOSConfig.XcodeProjectFile.createBuildSourceFile({
      project: modConfig.modResults,
      nativeProjectRoot: modConfig.modRequest.platformProjectRoot,
      filePath: `${projectName}/${PLUGIN_FILE_NAME}`,
      fileContents: OBJC_INTERCEPTOR_SOURCE,
      overwrite: true,
    });
    return modConfig;
  });
}

withIosRefreshCookieMerge.OBJC_INTERCEPTOR_SOURCE = OBJC_INTERCEPTOR_SOURCE;
withIosRefreshCookieMerge.normalizeIosCookieHeader = normalizeIosCookieHeader;

module.exports = withIosRefreshCookieMerge;
